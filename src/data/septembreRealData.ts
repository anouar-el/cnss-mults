/**
 * Convertit les données brutes de la base CNSS en entités typées SalarieReferentiel
 */
export function chargerBaseSalariesReelle(): SalarieReferentiel[] {
  return RAW_BASE_CNSS_SEPTEMBRE.map((item, index) => {
    const nomComplet = item.nom.trim();
    const situation = item.situation === 'so' ? 'SORTI' : item.situation === 'AT' ? 'ACCIDENT_TRAVAIL' : 'ACTIF';
    return {
      id: `sal_base_${index + 1}`,
      immatriculationCnss: normaliserCnss(item.cnss),
      cni: normaliserCni(item.cni),
      nomComplet,
      nomNormalise: normaliserNom(nomComplet),
      tokensNom: extraireTokensTries(nomComplet),
      situation,
      aliases: [],
    };
  });
}

/**
 * Convertit les données brutes du calcul salaire en entités typées LignePaieImportee
 */
export function chargerLignesPaieReelles(): LignePaieImportee[] {
  return RAW_CALCUL_SALAIRE_SEPTEMBRE.map((item, index) => {
    const nomBrut = item.nom.trim();
    return {
      id: `paie_sep_${index + 1}`,
      nomCompletBrut: nomBrut,
      nomNormalise: normaliserNom(nomBrut),
      tokensNom: extraireTokensTries(nomBrut),
      joursImportes: item.jours,
      salaireBase: item.base,
      salaireBrut: item.brut,
      ligneFichier: index + 2, // ligne 1 = entêtes
    };
  });
}
